# frozen_string_literal: true

require "digest"
require "fileutils"
require "json"
require "minitest/autorun"
require "open3"
require "tmpdir"
load File.expand_path("../scripts/materialize-opencode-node-modules", __dir__)

class MaterializeOpenCodeNodeModulesTest < Minitest::Test
  def test_materializes_root_and_nested_package_paths
    Dir.mktmpdir do |directory|
      bundle = File.join(directory, "bundle")
      source = File.join(directory, "source")
      FileUtils.mkdir_p([bundle, source])
      record = source_record(bundle, "fixture", "1.2.3", ["fixture", "parent/fixture"])
      audit = {
        "schema" => "opencode-source-acquisition/v1",
        "package" => "opencode",
         "release" => "1.18.8",
        "sources" => [record]
      }
      audit_path = File.join(directory, "audit.json")
      File.write(audit_path, JSON.generate(audit))
      workspace = File.join(source, "packages", "script")
      FileUtils.mkdir_p(workspace)
      File.write(File.join(workspace, "package.json"), JSON.generate({ "name" => "@opencode-ai/script" }))
      closure_path = write_closure(directory, audit_path, [{ "path" => "packages/script", "name" => "@opencode-ai/script", "version" => nil }])
      receipt = Agentlab::OpenCodeNodeModules.materialize!(
        source_audit_path: audit_path,
        closure_path: closure_path,
        bundle_root: bundle,
        source_root: source,
        receipt_path: File.join(directory, "receipt.json")
      )

      assert(File.file?(File.join(source, "node_modules", "fixture", "package.json")))
      assert(File.file?(File.join(source, "node_modules", "parent", "node_modules", "fixture", "package.json")))
      workspace_link = File.join(source, "node_modules", "@opencode-ai", "script")
      assert(File.symlink?(workspace_link))
      assert_equal(workspace, File.realpath(workspace_link))
      assert_equal(2, receipt.dig("scope", "package_paths"))
      assert_equal(1, receipt.dig("scope", "workspace_links"))
      refute(receipt.dig("validation", "package_manager_executed"))
    end
  end

  def test_rejects_workspace_identity_mismatch
    Dir.mktmpdir do |directory|
      bundle = File.join(directory, "bundle")
      source = File.join(directory, "source")
      FileUtils.mkdir_p([bundle, source])
      record = source_record(bundle, "fixture", "1.2.3", ["fixture"])
      audit = {
        "schema" => "opencode-source-acquisition/v1",
        "package" => "opencode",
       "release" => "1.18.8",
        "sources" => [record]
      }
      audit_path = File.join(directory, "audit.json")
      File.write(audit_path, JSON.generate(audit))
      workspace = File.join(source, "packages", "script")
      FileUtils.mkdir_p(workspace)
      File.write(File.join(workspace, "package.json"), JSON.generate({ "name" => "@opencode-ai/other" }))
      closure_path = write_closure(directory, audit_path, [{ "path" => "packages/script", "name" => "@opencode-ai/script", "version" => nil }])

      error = assert_raises(Agentlab::Error) do
        Agentlab::OpenCodeNodeModules.materialize!(
          source_audit_path: audit_path,
          closure_path: closure_path,
          bundle_root: bundle,
          source_root: source,
          receipt_path: File.join(directory, "receipt.json")
        )
      end
      assert_match(/workspace identity mismatch/, error.message)
    end
  end

  private

  def write_closure(directory, audit_path, workspaces)
    path = File.join(directory, "closure.json")
    File.write(path, JSON.generate({
      "schema" => "agentlab-opencode-source-closure/v1",
      "package" => "opencode",
       "release" => "1.18.8",
      "receipts" => {
        "source_audit" => {
          "sha256" => Digest::SHA256.file(audit_path).hexdigest
        }
      },
      "workspaces" => workspaces
    }))
    path
  end

  def source_record(bundle, name, version, package_paths)
    staging = File.join(File.dirname(bundle), "staging")
    package = File.join(staging, "package")
    FileUtils.mkdir_p(package)
    File.write(File.join(package, "package.json"), JSON.generate({ "name" => name, "version" => version }))
    archive = File.join(bundle, "sha512-#{'a' * 128}.tgz")
    FileUtils.mkdir_p(bundle)
    _output, error, status = Open3.capture3("tar", "-czf", archive, "-C", staging, "package")
    raise error unless status.success?
    {
      "archive" => File.basename(archive),
      "sha256" => Digest::SHA256.file(archive).hexdigest,
      "size" => File.size(archive),
      "npm_name" => name,
      "version" => version,
      "package_paths" => package_paths
    }
  end
end
